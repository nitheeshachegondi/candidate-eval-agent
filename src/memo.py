"""
Formats the agent's raw decision + trajectory into a memo a recruiter
could actually forward to a hiring manager — the artifact a human
would sign their name to, not a JSON blob.

This directly targets the "End to End Quality" rubric line: "produces
a final result the user can use... the finish of something a person
would sign their name to rather than an obvious AI generated draft."
"""

DECISION_LABELS = {
    "advance": "✅ ADVANCE",
    "reject": "❌ DO NOT ADVANCE",
    "reject_pending_verification": "⚠️ HOLD — NEEDS HUMAN FOLLOW-UP",
}

CONFIDENCE_NOTE = {
    "high": "High confidence — sources are consistent.",
    "medium": "Medium confidence — see the flag below before finalizing.",
    "low": "Low confidence — treat this as a starting point only.",
}


def build_memo(job: dict, case: dict, decision: dict) -> str:
    label = DECISION_LABELS.get(decision["decision"], decision["decision"])
    confidence_note = CONFIDENCE_NOTE.get(decision.get("confidence", "medium"), "")

    lines = [
        f"# Candidate Review — {case['id']}",
        "",
        f"**Recommendation: {label}**",
        f"*{confidence_note}*",
        "",
        "## Role",
        f"{job['title']}",
        "",
        "## What was reviewed",
        f"- **CV:** {case['cv_summary']}",
        f"- **Interview notes:** {case['interview_notes']}",
        f"- **Assessment:** {case['assessment_score']}",
        "",
        "## Why",
        decision.get("reasoning", "(no reasoning captured)"),
    ]

    if decision["decision"] == "reject_pending_verification":
        lines += [
            "",
            "## What a human reviewer should do next",
            "This case was flagged, not decided. A specific claim in one "
            "source could not be corroborated by another. Before making a "
            "final call:",
            "- Ask the candidate directly about the specific gap noted above",
            "- Check if a reference or portfolio piece can independently confirm the claim",
            "- If confirmed, treat as a clean advance; if not, treat as a clean reject",
        ]

    lines += [
        "",
        "---",
        "*Generated by the candidate-evaluation agent. This is a "
        "recommendation to support a human decision, not a final "
        "hiring decision.*",
    ]
    return "\n".join(lines)